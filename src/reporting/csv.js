/**
 * VERIDEX — CSV renderer.
 *
 * RFC 4180 quoting, UTF-8 BOM so Excel on a non-UTF-8 locale does not mangle device
 * names containing non-ASCII characters, and CRLF line endings for Windows
 * compatibility.
 */

import { flattenReport } from './model.js';

export const CSV_COLUMNS = Object.freeze([
  { key: 'section', header: 'Section' },
  { key: 'sectionStatus', header: 'Section status' },
  { key: 'field', header: 'Field' },
  { key: 'value', header: 'Value' },
  { key: 'status', header: 'Status' },
  { key: 'source', header: 'Source' },
  { key: 'confidence', header: 'Source confidence' },
  { key: 'collectedAt', header: 'Collected at' },
  { key: 'detail', header: 'Detail' },
  { key: 'notes', header: 'Notes' }
]);

/**
 * Quote a single CSV cell per RFC 4180.
 * @param {unknown} value
 * @returns {string}
 */
export function csvCell(value) {
  if (value === null || value === undefined) return '';
  const text = String(value);
  // Formula-injection guard: a leading =, +, - or @ is interpreted by spreadsheet
  // applications. Prefixing with an apostrophe keeps the text inert.
  const guarded = /^[=+\-@\t\r]/.test(text) ? `'${text}` : text;
  if (/[",\r\n]/.test(guarded)) return `"${guarded.replace(/"/g, '""')}"`;
  return guarded;
}

/**
 * Render the report as CSV.
 * @param {object} report
 * @returns {string}
 */
export function renderCsv(report) {
  const rows = flattenReport(report);
  const lines = [CSV_COLUMNS.map((column) => csvCell(column.header)).join(',')];

  // A header comment block would break RFC 4180 parsers, so report metadata goes in
  // dedicated columns' worth of rows at the top instead.
  lines.push(['VERIDEX report', report.meta.reportId, '', '', '', '', '', report.meta.generatedAt, '', `Generated by VERIDEX ${report.meta.appVersion} for ${report.meta.brand}`].map(csvCell).join(','));
  lines.push(['Device', report.meta.kind, '', '', '', '', '', report.meta.startedAt ?? '', '', report.meta.toolDisclaimer].map(csvCell).join(','));
  lines.push('');

  for (const row of rows) {
    lines.push(CSV_COLUMNS.map((column) => csvCell(row[column.key])).join(','));
  }

  if (report.manualResults.length > 0) {
    lines.push('');
    lines.push(['Manual inspection results', '', '', '', '', '', '', '', '', 'Recorded by the person performing the inspection, not by software.'].map(csvCell).join(','));
    for (const result of report.manualResults) {
      lines.push([csvCell('Manual inspection'), csvCell(result.status), csvCell(result.title), csvCell(result.status), csvCell(result.status), csvCell('manual observation'), csvCell('NONE'), csvCell(result.observedAt), '', csvCell(result.notes.join(' '))].join(','));
    }
  }

  // Excel-compatible: BOM + CRLF.
  return `\uFEFF${lines.join('\r\n')}\r\n`;
}
